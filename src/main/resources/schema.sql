-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============================================================
-- 海水养殖台账 V1：建池 -> 投苗 -> 日常记录 -> 抽检 -> 出池
-- 成本核算留待后续版本。所有语句幂等，可随应用反复启动执行。
-- ============================================================

-- 养殖池档案：水深、盐度、所属海区
CREATE TABLE IF NOT EXISTS t_aqua_pond (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_code VARCHAR(32) NOT NULL,
    pond_name VARCHAR(64) NOT NULL,
    sea_area VARCHAR(64) NOT NULL,
    water_depth_m DECIMAL(6,2) NOT NULL,
    salinity DECIMAL(6,2) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT '启用',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_aqua_pond_code UNIQUE (pond_code)
);

-- 投苗批次（原始投苗单，不可删除）：苗种来源、入池数量、计划出池日
CREATE TABLE IF NOT EXISTS t_aqua_seed_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no VARCHAR(32) NOT NULL,
    pond_id BIGINT NOT NULL,
    source VARCHAR(128) NOT NULL,
    quantity INT NOT NULL,
    stock_date DATE NOT NULL,
    planned_harvest_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT '在养',
    actual_harvest_date DATE,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_aqua_batch_no UNIQUE (batch_no),
    CONSTRAINT fk_aqua_batch_pond FOREIGN KEY (pond_id) REFERENCES t_aqua_pond (id)
);

-- 日常记录：按池按批留痕（水深/盐度日测值、备注）
CREATE TABLE IF NOT EXISTS t_aqua_daily_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    record_date DATE NOT NULL,
    water_depth_m DECIMAL(6,2),
    salinity DECIMAL(6,2),
    note VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_aqua_daily_pond FOREIGN KEY (pond_id) REFERENCES t_aqua_pond (id),
    CONSTRAINT fk_aqua_daily_batch FOREIGN KEY (batch_id) REFERENCES t_aqua_seed_batch (id)
);

-- 饲料投喂记录：按池按批留痕
CREATE TABLE IF NOT EXISTS t_aqua_feed_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    feed_date DATE NOT NULL,
    feed_name VARCHAR(64) NOT NULL,
    quantity_kg DECIMAL(10,2) NOT NULL,
    note VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_aqua_feed_pond FOREIGN KEY (pond_id) REFERENCES t_aqua_pond (id),
    CONSTRAINT fk_aqua_feed_batch FOREIGN KEY (batch_id) REFERENCES t_aqua_seed_batch (id)
);

-- 用药记录：按池按批留痕
CREATE TABLE IF NOT EXISTS t_aqua_medicine_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    use_date DATE NOT NULL,
    medicine_name VARCHAR(64) NOT NULL,
    dosage VARCHAR(64) NOT NULL,
    reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_aqua_med_pond FOREIGN KEY (pond_id) REFERENCES t_aqua_pond (id),
    CONSTRAINT fk_aqua_med_batch FOREIGN KEY (batch_id) REFERENCES t_aqua_seed_batch (id)
);

-- 换池转移记录
CREATE TABLE IF NOT EXISTS t_aqua_transfer_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    from_pond_id BIGINT NOT NULL,
    to_pond_id BIGINT NOT NULL,
    transfer_date DATE NOT NULL,
    quantity INT NOT NULL,
    reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_aqua_transfer_batch FOREIGN KEY (batch_id) REFERENCES t_aqua_seed_batch (id),
    CONSTRAINT fk_aqua_transfer_from FOREIGN KEY (from_pond_id) REFERENCES t_aqua_pond (id),
    CONSTRAINT fk_aqua_transfer_to FOREIGN KEY (to_pond_id) REFERENCES t_aqua_pond (id)
);

-- 抽检记录
CREATE TABLE IF NOT EXISTS t_aqua_inspection_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    inspect_date DATE NOT NULL,
    sample_count INT NOT NULL,
    avg_weight_g DECIMAL(10,2),
    result VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_aqua_insp_pond FOREIGN KEY (pond_id) REFERENCES t_aqua_pond (id),
    CONSTRAINT fk_aqua_insp_batch FOREIGN KEY (batch_id) REFERENCES t_aqua_seed_batch (id)
);

-- 出池记录
CREATE TABLE IF NOT EXISTS t_aqua_harvest_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    pond_id BIGINT NOT NULL,
    harvest_date DATE NOT NULL,
    quantity INT NOT NULL,
    destination VARCHAR(128),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_aqua_harvest_batch FOREIGN KEY (batch_id) REFERENCES t_aqua_seed_batch (id),
    CONSTRAINT fk_aqua_harvest_pond FOREIGN KEY (pond_id) REFERENCES t_aqua_pond (id)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('aqua-1', '海水养殖台账 V1：建池-投苗-日常-抽检-出池');
